"""Run actual R and record portable SHA-256 provenance; requires R packages."""

import argparse
import hashlib
import json
import os
import subprocess
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rscript", default="Rscript")
    parser.add_argument("--r-library", action="append", default=[])
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    env = os.environ.copy()
    if args.r_library:
        env["R_LIBS"] = os.pathsep.join(args.r_library)
    env["LC_ALL"] = "C"
    subprocess.run([args.rscript, "--vanilla", "reference/generate.R"],
                   cwd=root, env=env, check=True)
    # Normalize R's platform-specific output newlines before hashing. This does
    # not change reference numbers and matches the repository's LF checkout rule.
    for path in (root / "reference/outputs").glob("*.json"):
        path.write_bytes(path.read_bytes().replace(b"\r\n", b"\n"))
    paths = sorted(root.glob("datasets/*/*.csv")) + [
        root / "reference/generate.R", root / "reference/generate.py",
        root / "reference/make_inputs.py",
    ] + sorted((root / "reference/outputs").glob("*.json"))
    manifest = {
        "schema_version": 1,
        "generator": "Actual Rscript execution of reference/generate.R",
        "data_origin": "Original deterministic synthetic counts generated by make_inputs.py",
        "runtime": json.loads((root / "reference/outputs/runtime.json").read_text()),
        "sha256": {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                   for p in paths},
    }
    (root / "reference/manifest.json").write_text(
        json.dumps(manifest, indent=2, allow_nan=False) + "\n", encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    main()
